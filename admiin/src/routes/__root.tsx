function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <ThemeSync />
        {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
        <Outlet />
        <Toaster richColors position="top-right" />
      </AuthProvider>
    </QueryClientProvider>
  );
}

function ThemeSync() {
  useEffect(() => {
    const media = window.matchMedia("(prefers-color-scheme: dark)");
    let theme = "system";
    try {
      const saved = localStorage.getItem("nelma.ui.theme");
      if (saved === "light" || saved === "dark" || saved === "system") theme = saved;
    } catch {
      /* Respect system if storage is blocked. */
    }
    const apply = () => {
      const dark = theme === "dark" || (theme === "system" && media.matches);
      document.documentElement.classList.toggle("dark", dark);
      document.documentElement.style.colorScheme = dark ? "dark" : "light";
    };
    const change = (event: Event) => {
      const value: unknown = (event as CustomEvent<unknown>).detail;
      if (value === "light" || value === "dark" || value === "system") theme = value;
      apply();
    };
    apply();
    media.addEventListener("change", apply);
    window.addEventListener("nelma-theme-change", change);
    return () => {
      media.removeEventListener("change", apply);
      window.removeEventListener("nelma-theme-change", change);
    };
  }, []);
  return null;
}
